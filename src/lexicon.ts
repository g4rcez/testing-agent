// The words that step instructions and `assume` statements are read with, one lexicon per language.
// Adding a language is adding an entry here and its code to LANGUAGES: src/grammar.ts builds the patterns.
// Words are matched after folding (case, accents, spacing), so write them in any form; keep them Latin script.

export const LANGUAGES = ["en", "pt", "es"] as const;
export type Language = (typeof LANGUAGES)[number];

export type Lexicon = {
  // The generic noun comes before the name ("campo Email", "botão Pagar"), not after it ("Email field", "Pay button").
  nounFirst?: boolean;
  // Words that make an instruction conditional or negated; a literal reading would guess wrong.
  caution: string[];
  articles: string[];
  // "box", "field": the kind of control a field is named by.
  fieldNouns: string[];
  // "type X into the Y box": the word before the field, and the one before a purpose clause ("to search").
  into: string[];
  to: string[];
  // Verbs that start a typing step, and the form with the field in the middle ("fill the Y field with X").
  type: string[];
  fill: { verbs: string[]; with: string[] };
  pressEnter: { verbs: string[]; keys: string[] };
  // "select X in the Y dropdown": verbs, the words between option and field, and nouns for the dropdown.
  select: { verbs: string[]; links: string[]; nouns: string[] };
  toggle: { on: string[]; off: string[]; nouns: string[] };
  scroll: {
    verbs: string[];
    down: string[];
    up: string[];
    left: string[];
    right: string[];
    // Words before the container's name, the name of the page itself, and nouns for a container ("list").
    within: string[];
    page: string[];
    nouns: string[];
  };
  // Verbs of a click step and the word that may follow them ("click on X").
  click: { verbs: string[]; on: string[] };
  // "second", "last" (-1), and the suffixes of "2nd".
  ordinals: Record<string, number>;
  numbered: string[];
  // A word for a kind of control, and the role the page reports for it.
  kinds: Record<string, string>;
  // "X in the Y section": the words that say where, the nouns for a place, and for a row and what follows it.
  where: string[];
  places: string[];
  rows: string[];
  rowLinks: string[];
  // Role words that may trail (or lead) a label, and the words that start a trailing clause.
  roles: string[];
  clauses: string[];
  // "The Y box contains X", "The Y dropdown shows X", "The Y checkbox is checked".
  contains: string[];
  checked: string[];
  unchecked: string[];
  // Words a statement can drop before its words are looked for on the page.
  filler: string[];
};

